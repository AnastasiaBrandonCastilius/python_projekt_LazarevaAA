#Дано вещественное число А и целое число N (>0). Используя один цикл, найти значение выражения 1-А+А^2-A^3+...+(-1)^N*A^N. словный оператор не использовать.
A = input("Ввести первое число ")
N = input("Ввести второе целое число больше нуля ")
#проверка исключений

while type(A) !=float:
    try:
        A = float(A)
    except ValueError:
        print("Неправильно ввели первое значение!")
        A = input("Ввести ЧИСЛО ")
while type(N) !=int:
    try:
        N = int(N)
    except ValueError:
        print("Неправильно ввели второе значение!")
        N = input("Ввести ЦЕЛОЕ ЧИСЛО ")
while int(N) < 0:
    print("Неправильно ввели второе значение!")
    N = input("Ввести БОЛЬШЕ НУЛЯ ")

N = int(N)
#дополнительные переменные
sing = -1 #смена знака
power = 1 #текущее число
summa = 1
term = 1 #текущий член
i = 1 #счётчик
for i in range(1, N+1):
    power *= A #степень
    term = sing * power
    summa += term
    sing = -sing
    i += 1
print("Результат: ", summa)